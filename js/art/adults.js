// Adult and special creatures. 16x16, 1-bit, bottom-aligned, facing front or right.
// Each one is built around a single silhouette idea so it can be told apart from the
// outline alone: star tuft, wings, round belly, horn + club tail, cloud, flat puddle.
// The specials amplify a signature of their origin adult so the link reads at a glance:
// byeolbit is narae's body with the plume turned into a floating star and the wings grown;
// haessal is dwinggul's three-spike bed hair opened into a full ring of rays, now on legs.
//
// Constraints the frames rely on (keep them when editing):
// - Frame order per creature: idle[0], idle[1], happy, upset, eat, sleep. idle[0] is the
//   portrait (dex, album), so it must be the most characteristic pose.
// - idle[1] differs from idle[0] by a one-row squash or bob only; feet and base stay put,
//   otherwise the 500 ms flip reads as a jump instead of breathing.
// - Eyes and mouths keep one clear dot (also diagonally) from the outline and from each
//   other, or they fuse into the outline on the dot matrix; angry brows may touch it on
//   purpose. Isolated dots are eyes, sleeping mouths and podong's navel only.
// - eat uses the same wedge as the young set (top lip, one dot for the back of the mouth,
//   bottom lip, outline left open on the right edge), because food is drawn to the right.
//   A dent in the outline read as damage, not as an open mouth.
// - happy always has the open D-shaped mouth (wide bar over a shorter bar), upset the slanted
//   brows over an arched frown, sleep two '##' dashes: the same vocabulary as js/art/young.js.
// - banjjak's star tuft is 5 dots across. At 7 it matched the width of the head top and read
//   as a propeller.
// - podong's eyes sit inside its cheek marks; directly above them the marks read as eye bags.
// - Adults leave row 0 empty; only the specials reach the top row.
