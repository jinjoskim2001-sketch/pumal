// Young creatures: egg, baby, two children, three teens (SPEC sections 4 and 12).
// Every bitmap is 16x16, '#' lit and '.' unlit, bottom-aligned on the last row, centred,
// facing right or front (the renderer flips for left).
//
// Growth line, so the family feels related: the baby's single leaf (mongsil) stays as the
// lively child's sprout (tongtong) or melts into the mellow child's drooping tip (mallang),
// then becomes the teens' attitude -- two neat leaves (saessak), one ear up and one flopped
// (kkabul), or a spiky fringe on a leaning body (ppittak).
//
// idle[0] and idle[1] differ only by a one-row squash or bob so the pair reads as one creature
// breathing (tongtong and kkabul bob the whole body by one row). Eat frames face right with
// the mouth open as a wedge on the right edge, so the food item belongs to the creature's right.
// The baby's eyes are single dots on purpose; they are not stray pixels.
//
// Shared vocabulary with js/art/adults.js: happy = open D-shaped mouth (wide bar over a shorter
// bar) with limbs or head feature up, upset = slanted brows over an arched frown, sleep = two
// '##' dashes on a flattened body.
// kkabul never shows two upright ears (happy keeps one up and flings the floppy one sideways),
// and mallang's tip never stands straight up: both poses read as other, well-known characters.
// saessak's wilted leaves are thin arcs with air under them; solid leaves resting on the head
// read as a helmet.
