// Interface glyphs for the LCD: menu icons, in-matrix items, and the two bitmap fonts.
// Data only. A bitmap is an array of equal-length strings, '#' lit and '.' unlit.
//
// Icons are drawn by the renderer as solid segment glyphs (no dot gaps), about 3 CSS px per
// cell, and spend most of their life at ghost alpha. They are therefore built from solid
// masses, 2-dot strokes and cut-outs; hairline detail disappears at that size and contrast.
//
// Items are drawn as matrix dots next to 16x16 creatures. Everything that carries meaning by
// its outline (hands, falling items, meter marks) is kept solid-versus-hollow or
// tall-versus-squat so two glyphs never differ by a single dot.

